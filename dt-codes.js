function searchDTCodes(query) {
  if (!query || query.length < 2) return [];
  var q = query.trim().toLowerCase();
  return DT_CODES.filter(function(dt) {
    return (dt.c && dt.c.toLowerCase().includes(q)) ||
           (dt.r && dt.r.toLowerCase().includes(q)) ||
           (dt.p && dt.p.includes(query)) ||
           (dt.g && dt.g.toLowerCase().includes(q)) ||
           (dt.t && dt.t.toLowerCase().includes(q));
  });
}

